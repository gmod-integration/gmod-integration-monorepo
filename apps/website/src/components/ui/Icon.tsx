export type IconName = keyof typeof icons

export interface IconProps extends Omit<JSX.SvgSVGAttributes<SVGSVGElement>, 'name' | 'children'> {
  name: IconName
  size?: number | string
  strokeWidth?: number | string
}

export function Icon(props: IconProps) {
  const [local, rest] = splitProps(props, ['name', 'size', 'strokeWidth', 'class'])
  return (
    <Dynamic
      component={icons[local.name]}
      size={local.size ?? 18}
      strokeWidth={local.strokeWidth ?? 1.8}
      class={`ui-icon ${local.class ?? ''}`}
      aria-hidden="true"
      data-icon={local.name}
      {...rest}
    />
  )
}
